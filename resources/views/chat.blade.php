    <script>
        document.addEventListener('DOMContentLoaded', () => {
            const STORAGE_KEY = 'llm_chat_history';

            // Change this to your actual Laravel API endpoint.
            const CHAT_ENDPOINT = '/api/chat';

            const sidebar = document.getElementById('chatSidebar');
            const overlay = document.getElementById('sidebarOverlay');
            const historyContainer = document.getElementById('chatHistory');
            const historySearch = document.getElementById('historySearch');
            const messagesContainer = document.getElementById('messagesContainer');
            const welcomeScreen = document.getElementById('welcomeScreen');
            const chatContent = document.getElementById('chatContent');
            const messageInput = document.getElementById('messageInput');
            const chatForm = document.getElementById('chatForm');
            const sendBtn = document.getElementById('sendBtn');
            const headerTitle = document.getElementById('headerTitle');

            let conversations = JSON.parse(localStorage.getItem(STORAGE_KEY) || '[]');
            let currentChatId = null;
            let isSending = false;

            function saveHistory() {
                localStorage.setItem(STORAGE_KEY, JSON.stringify(conversations));
            }

            function getCurrentChat() {
                return conversations.find(chat => chat.id === currentChatId);
            }

            function createChat() {
                const chat = {
                    id: crypto.randomUUID(),
                    title: 'New Conversation',
                    messages: [],
                    createdAt: new Date().toISOString()
                };

                conversations.unshift(chat);
                currentChatId = chat.id;

                saveHistory();
                renderHistory();
                renderMessages();

                messageInput.focus();
            }

            function renderHistory() {
                const query = historySearch.value.toLowerCase();

                historyContainer.innerHTML = '';

                const filtered = conversations.filter(chat =>
                    chat.title.toLowerCase().includes(query)
                );

                document.getElementById('historyCount').textContent = filtered.length;
                document.getElementById('emptyHistory').classList.toggle(
                    'hidden', filtered.length > 0
                );

                filtered.forEach(chat => {
                    const item = document.createElement('div');
                    item.className =
                        `history-item group flex items-center gap-2 px-3 py-3 rounded-xl cursor-pointer hover:bg-slate-100 dark:hover:bg-slate-800 transition ${chat.id === currentChatId ? 'active' : ''}`;

                    const title = document.createElement('span');
                    title.className = 'text-xs font-medium truncate flex-1';
                    title.textContent = chat.title;

                    const deleteBtn = document.createElement('button');
                    deleteBtn.className =
                        'w-7 h-7 shrink-0 rounded-lg text-slate-400 hover:text-rose-500 hover:bg-rose-50 dark:hover:bg-rose-950/30 opacity-0 group-hover:opacity-100 transition';
                    deleteBtn.innerHTML = '<i class="fa-solid fa-trash-can text-[10px]"></i>';
                    deleteBtn.title = 'Delete conversation';

                    item.innerHTML = '<i class="fa-regular fa-message text-xs opacity-60"></i>';
                    item.append(title, deleteBtn);

                    item.addEventListener('click', () => {
                        currentChatId = chat.id;
                        renderHistory();
                        renderMessages();
                    });

                    deleteBtn.addEventListener('click', (e) => {
                        e.stopPropagation();

                        conversations = conversations.filter(c => c.id !== chat.id);

                        if (currentChatId === chat.id) {
                            currentChatId = null;
                        }

                        saveHistory();
                        renderHistory();
                        renderMessages();
                    });

                    historyContainer.appendChild(item);
                });
            }

            function renderMessages() {
                const chat = getCurrentChat();

                messagesContainer.innerHTML = '';

                if (!chat || chat.messages.length === 0) {
                    welcomeScreen.classList.remove('hidden');
                    messagesContainer.classList.add('hidden');
                    headerTitle.textContent = 'New Conversation';
                    document.getElementById('clearChatBtn').classList.add('hidden');
                    return;
                }

                welcomeScreen.classList.add('hidden');
                messagesContainer.classList.remove('hidden');
                headerTitle.textContent = chat.title;
                document.getElementById('clearChatBtn').classList.remove('hidden');

                chat.messages.forEach(message => {
                    appendMessage(message.role, message.content);
                });

                scrollToBottom();
            }

            function appendMessage(role, content) {
                const isUser = role === 'user';

                const wrapper = document.createElement('div');
                wrapper.className = `flex gap-4 ${isUser ? 'flex-row-reverse' : ''}`;

                const avatar = document.createElement('div');
                avatar.className =
                    `w-9 h-9 shrink-0 rounded-xl flex items-center justify-center text-white text-sm ${isUser ? 'bg-slate-600' : 'bg-gradient-to-br from-blue-600 to-indigo-600 shadow-md shadow-blue-500/20'}`;
                avatar.innerHTML = isUser ?
                    '<i class="fa-solid fa-user"></i>' :
                    '<i class="fa-solid fa-robot"></i>';

                const body = document.createElement('div');
                body.className = `min-w-0 max-w-[85%] space-y-2 ${isUser ? 'text-right' : ''}`;

                const label = document.createElement('p');
                label.className = 'text-xs font-bold text-slate-500 dark:text-slate-400';
                label.textContent = isUser ? 'You' : 'AI Assistant';

                const bubble = document.createElement('div');
                bubble.className = `message-content text-sm text-left ${isUser
            ? 'inline-block bg-blue-600 text-white rounded-2xl rounded-tr-sm px-4 py-3'
            : 'text-slate-700 dark:text-slate-200'}`;

                // Use textContent to avoid injecting untrusted HTML from the model.
                bubble.textContent = content;

                body.append(label, bubble);
                wrapper.append(avatar, body);
                messagesContainer.appendChild(wrapper);

                return bubble;
            }

            function showTyping() {
                const wrapper = document.createElement('div');
                wrapper.id = 'typingIndicator';
                wrapper.className = 'flex gap-4';

                wrapper.innerHTML = `
            <div class="w-9 h-9 shrink-0 rounded-xl bg-gradient-to-br from-blue-600 to-indigo-600 text-white flex items-center justify-center">
                <i class="fa-solid fa-robot text-sm"></i>
            </div>
            <div class="flex items-center gap-1.5 py-3">
                <span class="typing-dot w-2 h-2 rounded-full bg-blue-500"></span>
                <span class="typing-dot w-2 h-2 rounded-full bg-blue-500"></span>
                <span class="typing-dot w-2 h-2 rounded-full bg-blue-500"></span>
            </div>
        `;

                messagesContainer.appendChild(wrapper);
                scrollToBottom();
            }

            function scrollToBottom() {
                chatContent.scrollTop = chatContent.scrollHeight;
            }

            function setLoading(loading) {
                isSending = loading;
                messageInput.disabled = loading;
                sendBtn.disabled = loading;
                sendBtn.innerHTML = loading ?
                    '<i class="fa-solid fa-spinner fa-spin"></i>' :
                    '<i class="fa-solid fa-arrow-up"></i>';
            }

            async function sendMessage(content) {
                if (!content.trim() || isSending) return;

                if (!currentChatId) {
                    createChat();
                }

                const chat = getCurrentChat();

                const userMessage = {
                    role: 'user',
                    content: content.trim()
                };

                chat.messages.push(userMessage);

                if (chat.messages.filter(m => m.role === 'user').length === 1) {
                    chat.title = content.trim().slice(0, 35) +
                        (content.trim().length > 35 ? '...' : '');
                }

                saveHistory();
                renderHistory();
                renderMessages();

                messageInput.value = '';
                messageInput.style.height = 'auto';

                setLoading(true);
                showTyping();

                try {
                    const response = await fetch(CHAT_ENDPOINT, {
                        method: 'POST',
                        headers: {
                            'Content-Type': 'application/json',
                            'Accept': 'application/json',
                            'X-CSRF-TOKEN': document.querySelector('meta[name="csrf-token"]')
                                ?.content || ''
                        },
                        body: JSON.stringify({
                            message: userMessage.content,
                            conversation_id: chat.id,
                            history: chat.messages.slice(0, -1)
                        })
                    });

                    if (!response.ok) {
                        throw new Error(`Request failed (${response.status})`);
                    }

                    const data = await response.json();

                    if (!data.reply) {
                        throw new Error('Invalid response from AI server.');
                    }

                    chat.messages.push({
                        role: 'assistant',
                        content: data.reply
                    });

                    saveHistory();

                } catch (error) {
                    chat.messages.push({
                        role: 'assistant',
                        content: `Unable to get a response from the AI server. ${error.message}`
                    });
                } finally {
                    document.getElementById('typingIndicator')?.remove();
                    setLoading(false);
                    renderHistory();
                    renderMessages();
                    messageInput.focus();
                }
            }

            // New conversation
            document.getElementById('newChatBtn').addEventListener('click', createChat);

            // Clear current conversation
            document.getElementById('clearChatBtn').addEventListener('click', () => {
                const chat = getCurrentChat();
                if (!chat) return;

                chat.messages = [];
                chat.title = 'New Conversation';

                saveHistory();
                renderHistory();
                renderMessages();
            });

            // Search history
            historySearch.addEventListener('input', renderHistory);

            // Send message
            chatForm.addEventListener('submit', e => {
                e.preventDefault();
                sendMessage(messageInput.value);
            });

            // Keyboard shortcuts
            messageInput.addEventListener('keydown', e => {
                if (e.key === 'Enter' && !e.shiftKey) {
                    e.preventDefault();
                    chatForm.requestSubmit();
                }
            });

            // Auto-resize textarea
            messageInput.addEventListener('input', () => {
                messageInput.style.height = 'auto';
                messageInput.style.height = Math.min(messageInput.scrollHeight, 192) + 'px';
            });

            // Suggestion cards
            document.querySelectorAll('.suggestion-card').forEach(button => {
                button.addEventListener('click', () => {
                    messageInput.value = button.dataset.prompt;
                    messageInput.focus();
                    messageInput.style.height = 'auto';
                    messageInput.style.height = Math.min(messageInput.scrollHeight, 192) + 'px';
                });
            });

            // Mobile sidebar
            function closeSidebar() {
                sidebar.classList.add('hidden');
                overlay.classList.add('hidden');
            }

            document.getElementById('openSidebar').addEventListener('click', () => {
                sidebar.classList.remove('hidden');
                sidebar.classList.add('fixed', 'inset-y-0', 'left-0', 'z-40');
                overlay.classList.remove('hidden');
            });

            document.getElementById('closeSidebar').addEventListener('click', closeSidebar);
            overlay.addEventListener('click', closeSidebar);

            // Initial render
            renderHistory();

            if (conversations.length > 0) {
                currentChatId = conversations[0].id;
            }

            renderMessages();
        });
    </script>
